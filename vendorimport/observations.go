package vendorimport

import (
	"errors"
	"fmt"
	"io/fs"
	"os"
	"path/filepath"
	"reflect"
	"slices"
	"strings"
	"time"

	"go.yaml.in/yaml/v3"

	"github.com/mrwiora/tpm2-verifier/vendorinfo"
)

// ObservationsFile is the file in a vendor directory recording the TPMs seen
// in submissions. It holds nothing that identifies a device.
const ObservationsFile = "observations.yaml"

// Observation is what one submission tells about a vendor: firmware, NV
// layout and the structure of the EK chains.
type Observation struct {
	Firmware     string       `yaml:"firmware" json:"firmware"`
	VendorString string       `yaml:"vendor_string,omitempty" json:"vendor_string,omitempty"`
	Spec         string       `yaml:"spec,omitempty" json:"spec,omitempty"`
	NV           []string     `yaml:"nv,flow" json:"nv"`
	EK           []ObservedEK `yaml:"ek" json:"ek"`
	FirstSeen    string       `yaml:"first_seen" json:"first_seen"`
}

// ObservedEK is the structure of one EK certificate chain.
type ObservedEK struct {
	Index     string   `yaml:"index" json:"index"`
	Label     string   `yaml:"label" json:"label"`
	Levels    int      `yaml:"levels" json:"levels"`
	Structure string   `yaml:"structure" json:"structure"`
	Model     string   `yaml:"model,omitempty" json:"model,omitempty"`
	Version   string   `yaml:"version,omitempty" json:"version,omitempty"`
	Quirks    []string `yaml:"quirks,omitempty,flow" json:"quirks,omitempty"`
}

func observe(info *vendorinfo.Info, now time.Time) Observation {
	if now.IsZero() {
		now = time.Now()
	}
	t := info.TPM
	o := Observation{Firmware: t.FirmwareVersion, VendorString: t.VendorString, FirstSeen: now.UTC().Format(time.DateOnly)}
	if t.Family != "" {
		o.Spec = fmt.Sprintf("TPM %s rev %s", t.Family, t.SpecRevision)
	}
	for _, n := range info.NV {
		if !strings.HasPrefix(n.Index, "0x01C") { // TCG range
			continue
		}
		s := n.Index + " " + n.Label
		if !slices.Contains(strings.Split(n.Attributes, "|"), "written") {
			s += " (not written)"
		}
		o.NV = append(o.NV, s)
	}
	for _, ek := range info.EK {
		e := ObservedEK{Index: ek.Index, Label: ek.Label, Levels: ek.Structure.Levels, Structure: ek.Structure.Summary}
		if len(ek.Chain) > 0 {
			if tp := ek.Chain[0].TPM; tp != nil {
				e.Model, e.Version = tp.Model, tp.Version
			}
		}
		for _, c := range ek.Chain {
			for _, q := range c.Quirks {
				code := q.Code
				if c.Depth == 0 {
					code = "ek:" + code
				}
				if !slices.Contains(e.Quirks, code) {
					e.Quirks = append(e.Quirks, code)
				}
			}
		}
		slices.Sort(e.Quirks)
		o.EK = append(o.EK, e)
	}
	return o
}

// same compares observations without the date.
func (o Observation) same(x Observation) bool {
	a, b := o, x
	a.FirstSeen, b.FirstSeen = "", ""
	return reflect.DeepEqual(a, b)
}

func readObservations(vendors, id string) ([]Observation, error) {
	data, err := os.ReadFile(filepath.Join(vendors, id, ObservationsFile))
	if errors.Is(err, fs.ErrNotExist) {
		return nil, nil
	}
	if err != nil {
		return nil, err
	}
	var obs []Observation
	if err := yaml.Unmarshal(data, &obs); err != nil {
		return nil, fmt.Errorf("%s/%s: %w", id, ObservationsFile, err)
	}
	return obs, nil
}

func encodeObservations(obs []Observation) ([]byte, error) {
	var b strings.Builder
	b.WriteString("# Generated by tpm2-ek vendor import from submitted debug bundles and\n" +
		"# debug-anon output. No device specific data. Do not edit by hand.\n")
	enc := yaml.NewEncoder(&b)
	enc.SetIndent(2)
	if err := enc.Encode(obs); err != nil {
		return nil, err
	}
	return []byte(b.String()), nil
}

// Markers of the generated part of a vendor README.md.
const (
	readmeBegin = "<!-- BEGIN observations: generated by tpm2-ek vendor import, do not edit -->"
	readmeEnd   = "<!-- END observations -->"
)

func observationsMarkdown(obs []Observation) string {
	var b strings.Builder
	b.WriteString(readmeBegin + "\n\n## Observed TPMs\n\n")
	b.WriteString("From submitted debug bundles and debug-anon output (see `observations.yaml`).\n\n")
	b.WriteString("| Firmware | Vendor string | EK | Levels | Chain (root first) | Quirks | First seen |\n|---|---|---|---|---|---|---|\n")
	for _, o := range obs {
		for _, e := range o.EK {
			fmt.Fprintf(&b, "| %s | %s | `%s` %s | %d | %s | %s | %s |\n",
				o.Firmware, o.VendorString, e.Index, e.Label, e.Levels, e.Structure, strings.Join(e.Quirks, ", "), o.FirstSeen)
		}
		if len(o.EK) == 0 {
			fmt.Fprintf(&b, "| %s | %s | none | | | | %s |\n", o.Firmware, o.VendorString, o.FirstSeen)
		}
	}
	b.WriteString("\n" + readmeEnd + "\n")
	return b.String()
}

// updateReadme replaces the generated block of a README, or appends it.
func updateReadme(readme, block string) string {
	i := strings.Index(readme, readmeBegin)
	j := strings.Index(readme, readmeEnd)
	if i >= 0 && j > i {
		end := j + len(readmeEnd)
		if end < len(readme) && readme[end] == '\n' {
			end++
		}
		return readme[:i] + block + readme[end:]
	}
	if readme != "" && !strings.HasSuffix(readme, "\n\n") {
		readme = strings.TrimRight(readme, "\n") + "\n\n"
	}
	return readme + block
}
