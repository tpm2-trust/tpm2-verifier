// TCG vendor IDs (TCG Vendor ID Registry) of common TPM manufacturers.
var vendorNames = map[string]string{
	"AMD": "AMD", "ATML": "Atmel", "BRCM": "Broadcom", "CSCO": "Cisco", "FLYS": "Flyslice Technologies",
	"GOOG": "Google", "HPE": "Hewlett Packard Enterprise", "IBM": "IBM", "IFX": "Infineon Technologies",
	"INTC": "Intel Corporation", "LEN": "Lenovo", "MSFT": "Microsoft", "NSM": "National Semiconductor",
	"NTC": "Nuvoton Technology", "NTZ": "Nationz Technologies", "QCOM": "Qualcomm", "ROCC": "Fuzhou Rockchip",
	"SMSC": "SMSC", "SMSN": "Samsung", "SNS": "Sinosun", "STM": "STMicroelectronics", "TXN": "Texas Instruments",
	"WEC": "Winbond", "SECE": "SecEdge", "HISI": "Huawei",
}

type draftCert struct {
	file, subject, source, sha256 string
	root                          bool
}

// buildDraft creates vendor/<id>/: vendor.yaml, README.md and the public CA
// certificates of the chains that are not in the store yet.
func (info *Info) buildDraft(s *tpm.Scan, eks []EKReport, st *store.Store, created time.Time) error {
	m := s.Info.Manufacturer
	id := slug(m)
	if id == "" {
		id = "unknown"
	}
	name := vendorNames[m]
	if name == "" {
		name = m
	}
	existing := st.VendorForManufacturer(m)
	if existing != nil {
		id, name = existing.ID, existing.Name
	}
	dir := "vendor/" + id
	info.Draft = dir

	var certs []draftCert
	seen := map[string]bool{}
	used := map[string]bool{}
	var critical []string
	for i, r := range eks {
		for j, l := range r.Report.Chain {
			for _, o := range l.Cert.UnhandledCriticalExtensions {
				if !contains(critical, o.String()) {
					critical = append(critical, o.String())
				}
			}
			d := info.EK[i].Chain[j]
			if !d.Public || !d.CA || d.StorePath != "" || seen[d.SHA256] {
				continue
			}
			seen[d.SHA256] = true
			root := l.Cert.IsSelfSigned()
			role := "intermediates"
			if root {
				role = "roots"
			}
			base := slug(commonName(l.Cert))
			if base == "" {
				base = "ca"
			}
			file := role + "/" + base + ".der"
			for n := 2; used[file]; n++ {
				file = fmt.Sprintf("%s/%s-%d.der", role, base, n)
			}
			used[file] = true
			src := d.URL
			if src == "" {
				src = "TPM NV (included on request)"
			}
			certs = append(certs, draftCert{file: file, subject: d.Subject, source: src, sha256: d.SHA256, root: root})
			info.files[dir+"/"+file] = l.Cert.Raw
		}
	}
	var chainIdx []string
	for _, e := range s.Entries {
		if e.Label.Kind == tpm.KindEKChain && len(e.Certificates) > 0 {
			chainIdx = append(chainIdx, tpm.HexIndex(e.Index))
		}
	}

	var y strings.Builder
	fmt.Fprintf(&y, "# Draft generated by tpm2-ek debug-anon on %s. Review before use:\n", info.Created)
	fmt.Fprintf(&y, "# compare every root fingerprint with one published by the vendor through an\n# independent channel; certificates downloaded via AIA are not authenticated.\n")
	if existing != nil {
		fmt.Fprintf(&y, "# Vendor %q is already in the store; this overlay adds what was missing.\n", id)
	}
	fmt.Fprintf(&y, "id: %s\nname: %s\n", id, quote(name))
	fmt.Fprintf(&y, "# TPM2_PT_MANUFACTURER as returned by TPM2_GetCapability.\nmanufacturer_ids: [%s]\n", m)
	desc := "TPM vendor string " + quote(s.Info.VendorString) + ", firmware " + s.Info.FirmwareVersion + "."
	fmt.Fprintf(&y, "description: %s\n", quote("TODO. Seen with "+desc))
	if len(chainIdx) > 0 {
		fmt.Fprintf(&y, "# NV indices holding (device specific) chain certificates as concatenated DER.\nchain_nv_indices: [%s]\n", strings.Join(chainIdx, ", "))
	}
	if len(critical) > 0 {
		fmt.Fprintf(&y, "# Critical extensions not handled by the verifier, seen in the chain.\n# Accept them only after review:\n# accepted_critical_extensions: [%s]\n", strings.Join(quoteAll(critical), ", "))
	}
	if len(certs) == 0 {
		fmt.Fprintf(&y, "certificates: []\n")
	} else {
		fmt.Fprintf(&y, "certificates:\n")
	}
	for _, c := range certs {
		role := "intermediate"
		if c.root {
			role = "root"
		}
		fmt.Fprintf(&y, "  - file: %s\n    role: %s\n    subject: %s\n    source: %s\n    sha256: %s\n    retrieved: %s\n",
			c.file, role, quote(c.subject), quote(c.source), c.sha256, info.Created)
	}
	info.files[dir+"/vendor.yaml"] = []byte(y.String())
	info.files[dir+"/README.md"] = []byte(info.readme(name, chainIdx, certs))
	return nil
}

func (info *Info) readme(name string, chainIdx []string, certs []draftCert) string {
	var b strings.Builder
	t := info.TPM
	fmt.Fprintf(&b, "# %s\n\nDraft generated by `tpm2-ek debug-anon` on %s.\n\n", name, info.Created)
	fmt.Fprintf(&b, "## TPM\n\n| Property | Value |\n|---|---|\n| Manufacturer | %s |\n| Vendor string | %s |\n| Firmware | %s |\n| Specification | TPM %s, revision %s |\n\n",
		t.Manufacturer, t.VendorString, t.FirmwareVersion, t.Family, t.SpecRevision)
	fmt.Fprintf(&b, "## NV indices (TCG range)\n\n| Index | Content | Attributes | Size |\n|---|---|---|---|\n")
	for _, n := range info.NV {
		if !strings.HasPrefix(n.Index, "0x01C") {
			continue
		}
		fmt.Fprintf(&b, "| `%s` | %s | `%s` | %d |\n", n.Index, n.Label, strings.ReplaceAll(n.Attributes, "|", "\\|"), n.Size)
	}
	if len(chainIdx) > 0 {
		fmt.Fprintf(&b, "\nChain certificates are stored in %s.\n", strings.Join(chainIdx, ", "))
	}
	for _, ek := range info.EK {
		fmt.Fprintf(&b, "\n## Hierarchy of %s (%s)\n\nStatus at creation: **%s**\n\n", ek.Index, ek.Label, ek.Status)
		for i := len(ek.Chain) - 1; i >= 0; i-- {
			c := ek.Chain[i]
			kind := "device specific (from the TPM)"
			switch {
			case c.StorePath != "":
				kind = "store: " + c.StorePath
			case c.Public && c.URL != "":
				kind = "published at " + c.URL
			case c.Public:
				kind = "from the TPM, included on request"
			}
			fmt.Fprintf(&b, "%s- `%s` — %s, %s, %d days\n", strings.Repeat("  ", len(ek.Chain)-1-i), c.Subject, kind, c.KeyAlgorithm, c.ValidityDays)
		}
		last := ek.Chain[len(ek.Chain)-1]
		if ek.Status == verify.StatusIncomplete {
			fmt.Fprintf(&b, "\nThe chain is incomplete: no certificate for the issuer `%s` was found.", last.Issuer)
			if len(last.AIAIssuers) > 0 {
				fmt.Fprintf(&b, " Its AIA URL: %s.", strings.Join(last.AIAIssuers, ", "))
			}
			fmt.Fprintf(&b, " Obtain it from the vendor and add it.\n")
		}
		var quirks []string
		for _, c := range ek.Chain {
			for _, q := range c.Quirks {
				quirks = append(quirks, fmt.Sprintf("- depth %d `%s`: %s (%s)", c.Depth, c.Subject, q.Code, q.Detail))
			}
		}
		if len(quirks) > 0 {
			fmt.Fprintf(&b, "\nQuirks:\n\n%s\n", strings.Join(quirks, "\n"))
		}
		if ek := ek.Chain[0]; ek.TPM != nil {
			fmt.Fprintf(&b, "\nEK subjectAltName: manufacturer `%s`, model `%s`, version `%s`.\n", ek.TPM.ManufacturerRaw, ek.TPM.Model, ek.TPM.Version)
		}
	}
	if len(certs) > 0 {
		fmt.Fprintf(&b, "\n## Certificates in this draft\n\n| File | Subject | SHA-256 | Source |\n|---|---|---|---|\n")
		for _, c := range certs {
			fmt.Fprintf(&b, "| `%s` | %s | `%s` | %s |\n", c.file, c.subject, c.sha256, c.source)
		}
	}
	return b.String()
}

func commonName(c *certparse.Certificate) string {
	switch {
	case c.Subject.CommonName != "" && !strings.Contains(c.Subject.CommonName, "."):
		return c.Subject.CommonName
	case len(c.Subject.OrganizationalUnit) > 0:
		return c.Subject.OrganizationalUnit[0]
	}
	return c.Subject.CommonName
}

func slug(s string) string {
	var b strings.Builder
	dash := false
	for _, r := range strings.ToLower(s) {
		if r >= 'a' && r <= 'z' || r >= '0' && r <= '9' {
			b.WriteRune(r)
			dash = false
		} else if !dash && b.Len() > 0 {
			b.WriteByte('-')
			dash = true
		}
	}
	return strings.TrimSuffix(b.String(), "-")
}

// quote returns s as a YAML double quoted scalar.
func quote(s string) string {
	var b strings.Builder
	enc := json.NewEncoder(&b)
	enc.SetEscapeHTML(false)
	enc.Encode(s)
	return strings.TrimSuffix(b.String(), "\n")
}

func quoteAll(ss []string) []string {
	out := make([]string, len(ss))
	for i, s := range ss {
		out[i] = quote(s)
	}
	return out
}

func contains(ss []string, s string) bool {
	for _, x := range ss {
		if x == s {
			return true
		}
	}
	return false
}
